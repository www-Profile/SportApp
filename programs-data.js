function ex(name, reps, sets, options = {}) {
    return { name, reps, sets, ...options };
}


function getProgramWorkoutCount(program) {
    if (!program) return 0;

    // Личные программы с назначениями на конкретные дни
    if (Array.isArray(program.dayWorkouts)) {
        return program.dayWorkouts.filter(Boolean).length;
    }

    const pattern = Array.isArray(program.weekPattern) &&
        program.weekPattern.length === 7
        ? program.weekPattern
        : (PROGRAM_WORKOUTS[program.id]?.weekPattern ||
            [true, false, true, false, true, false, false]);

    let count = 0;

    for (let day = 0; day < program.durationDays; day++) {
        if (pattern[day % 7]) count++;
    }

    return count;
}


function buildProgramWorkout(programId, dayNumber) {
    const program = PROGRAM_WORKOUTS[programId];
    if (!program || !Array.isArray(program.weeklyPlan)) return null;
    const dayIndex = (dayNumber - 1) % 7;
    const dayPlan = program.weeklyPlan[dayIndex];
    if (!dayPlan) return null;

    const weekNumber = Math.ceil(dayNumber / 7);
    const phase = weekNumber <= 2 ? 0 : weekNumber <= 4 ? 1 : weekNumber <= 7 ? 2 : 3;
    const workoutItems = [...dayPlan.exercises, ...(dayPlan.extraExercises || [])];

    // Не выдаём весь объём с первой недели: добавляем по одному упражнению
    // каждую неделю, пока тренировка не достигнет полного запланированного состава.
    const exerciseCount = Math.min(workoutItems.length, 5 + weekNumber - 1);
    const progressiveItems = workoutItems.slice(0, exerciseCount);

    const exercises = progressiveItems.map(item => {
        const variant = Array.isArray(item.variants)
            ? item.variants[Math.min(phase, item.variants.length - 1)]
            : item.name;
        const catalogExercise = findCatalogExercise(variant);
        if (!catalogExercise) {
            console.warn('[SportApp] Не найдено упражнение программы:', variant);
            return null;
        }

        // Подход добавляется каждые две недели, с ограничением по объёму.
        const sets = Math.min(item.maxSets || 4, item.sets + Math.floor((weekNumber - 1) / 2));
        let reps = item.reps;
        if (typeof reps === 'number') {
            const maxReps = item.maxReps || (item.reps >= 20 ? item.reps + 10 : 20);
            reps = Math.min(maxReps, item.reps + Math.floor((weekNumber - 1) * (item.increment || 1.5)));
        } else if (typeof reps === 'string' && /сек/.test(reps)) {
            const seconds = parseInt(reps, 10) || 15;
            reps = Math.min(item.maxSeconds || 50, seconds + (weekNumber - 1) * 3) + ' сек';
        }
        return { ...catalogExercise, sets, reps, programWeek: weekNumber };
    }).filter(Boolean);

    if (exercises.length < 5) {
        console.error('[SportApp] В тренировке меньше 5 упражнений:', programId, dayNumber, exercises.length);
        return null;
    }
    return { title: dayPlan.title, category: program.category || 'Всё тело', icon: program.icon || 'WholeBody', exercises };
}
